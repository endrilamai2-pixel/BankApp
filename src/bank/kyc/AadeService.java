package bank.kyc;

import java.util.Optional;

/** Αναζήτηση ΑΦΜ στο μητρώο της ΑΑΔΕ. Επιτρέπει εναλλαγή πραγματικής υπηρεσίας / δοκιμαστικών δεδομένων. */
public interface AadeService {

    /** Επιστρέφει empty αν το ΑΦΜ δεν βρεθεί· ρίχνει AadeException σε σφάλμα επικοινωνίας ή αυθεντικοποίησης. */
    Optional<AadeRecord> lookup(String afm);

    /** Περιγραφή της πηγής, για εμφάνιση στον χρήστη και στο ιστορικό ελέγχων. */
    String sourceName();

    /** Αληθές μόνο για την πραγματική υπηρεσία. Ένας έλεγχος με δοκιμαστικά δεδομένα ΔΕΝ είναι έλεγχος KYC. */
    boolean isLive();
}
